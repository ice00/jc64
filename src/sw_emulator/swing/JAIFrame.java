  /**
   * Reset the UI interface
   */
  private void resetUI() {
    jLabelEstimatedTokens.setText("Est. tokens: —");
    jLabelActualTokens.setText("Actual tokens: —");
    jLabelElapsedTime.setText("Elapsed: 00:00");
    jTextAreaStatus.setText("Ready");
    jButtonApply.setEnabled(false);

    // Replace result panel with a fresh one
    jPanelCn.removeAll();
    resultPanel = new LabelResultPanel();
    jPanelCn.add(resultPanel, BorderLayout.CENTER);
    jPanelCn.revalidate();
    jPanelCn.repaint();

    if (elapsedTimer != null && elapsedTimer.isRunning()) elapsedTimer.stop();
  }
  
  
  /**
   * Update the elapsed time
   */
  private void updateElapsed() {
    long secs = (System.currentTimeMillis() - startTimeMs) / 1000;
    jLabelElapsedTime.setText(String.format("Elapsed: %02d:%02d", secs / 60, secs % 60));
  }
  
  
  /**
   * Code to execute when the analysis is complete
   * 
   * @param suggestions the suggested labels
   * @param currentLabels the current valid labels
   */
  private void onAnalysisComplete(Map<String, String> suggestions,
                                  Map<String, String> currentLabels) {
    // Stop timer
    if (elapsedTimer != null) elapsedTimer.stop();
    updateElapsed();  // final value

    // Show actual token usage
    TokenUsage usage = analyzer.getLastTokenUsage();
    jLabelActualTokens.setText("Actual tokens: " + usage.getTotalTokens()
            + "  (prompt " + usage.getPromptTokens()
            + " + completion " + usage.getCompletionTokens() + ")");

    // Populate table
    resultPanel.setResults(suggestions, currentLabels);

    // Update status
    int count = suggestions.size();
    jTextAreaStatus.setText(count + " label" + (count == 1 ? "" : "s") + " found");
    jTextAreaStatus.setForeground(count > 0 ? new Color(0, 120, 0) : Color.GRAY);
    jButtonApply.setEnabled(count > 0);

    // Bring window to front
    bringToFront();
  }
  
 /**
  * To be executed on alalysis error
  * 
  * @param ex the exception
  */ 
 private void onAnalysisError(Exception ex) {
    if (elapsedTimer != null) elapsedTimer.stop();
    updateElapsed();

    jTextAreaStatus.setText("Error: " + ex.getMessage());
    jTextAreaStatus.setForeground(Color.RED);
    jButtonApply.setEnabled(false);

    bringToFront();
  }

 /**
  * To be executed on apply button pressed
  */
  private void onApply() {
    List<LabelTableModel.Row> selected = resultPanel.getSelectedRows();
    if (applyCallback != null) applyCallback.onApply(selected);
    setVisible(false);
  }

  /**
   * To be executed on cancel button pressed
   */
  private void onCancel() {
    if (elapsedTimer != null) elapsedTimer.stop();
    setVisible(false);
  }  

  // ---------------------------------------------------------------------------
  // Private – bring to front (works around Windows focus restrictions)
  // ---------------------------------------------------------------------------

  /**
   * Bring frame in front of main when analysis is finished
   */
  private void bringToFront() {
    // Standard approach
    setAlwaysOnTop(true);
    toFront();
    requestFocus();
    setAlwaysOnTop(false);  // release so it doesn't stay above everything

    // Taskbar flash (Windows): requesting focus on a non-focused window
    // triggers the orange taskbar flash automatically on Windows
  } 
   
