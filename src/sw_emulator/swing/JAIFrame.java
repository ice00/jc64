  /**
   * Starts an AI analysis in a background thread and updates the UI as it
   * progresses. Safe to call from the EDT.
   *
   * @param config        the configuration to use
   * @param source        disassembled source text to analyze
   * @param currentLabels labels currently present in the disassembler (addr->name)
   * @param knownLabels   labels found in previous calls (for context), may be null
   * @param callback      called on the EDT when the user clicks Apply
   */
  public void startAnalysis(AIBackendConfig config, CharSequence source,
                            Map<String, String> currentLabels,
                            Map<String, String> knownLabels,
                            ApplyCallback callback) {
    this.applyCallback = callback;

    // Reset UI
    resetUI();

    // Show estimated tokens immediately (no API call needed)
    int estimated = M6510LabelAnalyzer.estimateTokens(source);
    jLabelEstimatedTokens.setText("Est. tokens: " + estimated);

    // Backend info
    jLabelBackend.setText("Backend: " + config.getDisplayName()
            + "   Model: " + config.getModel());

    // Start elapsed timer
    startTimeMs = System.currentTimeMillis();
    elapsedTimer = new Timer(500, e -> updateElapsed());
    elapsedTimer.start();

    jTextAreaStatus.setText("Analyzing…");
    jButtonApply.setEnabled(false);

    // Launch background thread
    final String sourceSnap = source.toString();
    analyzer.analyzeLabelsAsync(config, 
            sourceSnap, knownLabels,
            suggestions -> SwingUtilities.invokeLater(() ->
                    onAnalysisComplete(suggestions, currentLabels)),
            error -> SwingUtilities.invokeLater(() ->
                    onAnalysisError(error)));
  }
  
